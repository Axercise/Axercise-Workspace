import assert from "node:assert/strict";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { execFileSync } from "node:child_process";
import { test } from "node:test";

test("writes to the selected local project, keeps versions, and rejects stale saves and paths outside it", async t => {
  const home = fs.mkdtempSync(path.join(os.tmpdir(), "axercise-code-test-"));
  t.after(() => fs.rmSync(home, { recursive: true, force: true }));
  process.env.AXERCISE_DATA_DIR = path.join(home, "data");
  const { browseCodeFolders, openProject, listCodeEntries, createCodeEntry, readCodeFile, saveCodeFile, checkpoint, codeVersions, readCodeVersion } = await import("../src/server/code-project");
  const dir = path.join(home, "โปรเจกต์ with spaces");
  const external = path.join(home, "external");
  fs.mkdirSync(dir);
  fs.mkdirSync(external);
  fs.writeFileSync(path.join(external, "outside.txt"), "outside");
  fs.writeFileSync(path.join(dir, ".env"), "fixture-only");
  fs.symlinkSync(external, path.join(dir, "junction"), process.platform === "win32" ? "junction" : "dir");
  const project = openProject(dir);
  assert.equal(openProject(`  "${dir}"  `).id, project.id);
  assert.throws(() => readCodeFile(project, "../external/outside.txt"));
  assert.throws(() => readCodeFile(project, "junction/outside.txt"));
  assert.throws(() => readCodeFile(project, ".env"));
  createCodeEntry(project, "src", "folder");
  assert.deepEqual(browseCodeFolders(dir).folders, [{ name: "src", directory: path.join(dir, "src") }]);
  assert.equal(browseCodeFolders(path.join(dir, "src")).parent, dir);
  assert.equal(browseCodeFolders(path.parse(dir).root).selectable, false);
  createCodeEntry(project, "src/demo.ts", "file");
  assert.deepEqual(listCodeEntries(project, "").map(entry => entry.path), ["src"]);
  assert.throws(() => createCodeEntry(project, "src/demo.ts", "file"));
  const filePath = path.join(dir, "src/demo.ts");
  const original = "\uFEFFexport const name = 'เดิม';\r\n";
  fs.writeFileSync(filePath, original);
  checkpoint(project, "src/demo.ts");
  const git = (...args: string[]) => execFileSync("git", args, { cwd: dir, stdio: "ignore", windowsHide: true });
  git("init", "-q");
  git("add", "--", "src/demo.ts");
  git("-c", "user.name=Fixture", "-c", "user.email=fixture@example.invalid", "-c", "commit.gpgsign=false", "-c", "core.hooksPath=.git/test-no-hooks", "commit", "-qm", "Initial file");
  const first = readCodeFile(project, "src/demo.ts");
  const updated = saveCodeFile(project, first.path, first.content.replace("เดิม", "ใหม่"), first.revision);
  assert.equal(fs.readFileSync(filePath, "utf8"), "\uFEFFexport const name = 'ใหม่';\r\n");
  const versions = await codeVersions(project, first.path);
  assert.equal(await readCodeVersion(project, first.path, "checkpoint"), original);
  assert.equal(await readCodeVersion(project, first.path, "previous"), original);
  const commit = versions.find(version => version.label.includes("Initial file"));
  assert.ok(commit);
  assert.equal((await readCodeVersion(project, first.path, commit.id)).replaceAll("\r\n", "\n"), original.replaceAll("\r\n", "\n"));
  fs.writeFileSync(filePath, "external edit");
  assert.throws(() => saveCodeFile(project, first.path, "do not overwrite", updated.revision), { status: 409 });
  assert.equal(fs.readFileSync(filePath, "utf8"), "external edit");
});
